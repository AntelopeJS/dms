const FIRST_PENDING_DOSSIER = 45601;

/** The dossiers waiting for their first drawing: Client_1 … Client_10. */
export function pendingDossiers(): AgendaPendingItem[] {
  return Array.from({ length: PENDING_COUNT }, (_, index) => {
    const dossier = String(FIRST_PENDING_DOSSIER + index);
    return {
      id: dossier,
      title: `Client_${index + 1}`,
      subtitle: "DC-Dessin-AP1",
      calendarId: "en-planning",
      durationSlots: 1,
      allowedResourceIds: groupMembers("dessinateurs"),
      data: {
        dossier,
        commune: `Commune_${index + 1}`,
        op: "DC",
        tache: "Dessin",
        sub: "AP1",
        statut: "en-planning",
        remarque: "",
      },
    };
  });
}
